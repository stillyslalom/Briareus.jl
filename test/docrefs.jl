# Documenter cross-reference guard, ported from CompactLES (test/docrefs_tests.jl).
# The docs build (`checkdocs = :exports`, `warnonly = false`) runs every tutorial and
# takes many minutes, and it has failed on cheap mistakes that need no build to see:
# an exported name whose docstring went to a helper because code came between the two,
# an `@ref` to a binding without a docstring, a src file whose docstrings no
# `@autodocs` block lists. This file resolves the docs the way Documenter will, without
# Literate, Documenter or the tutorials, in about a second once the package is loaded.
#
# What Documenter renders here: every docstring an `@autodocs` block selects, by the
# block's `Modules`, `Pages` (a docstring's source path must end with a listed page,
# Documenter's `endswith(normpath(path), normpath(page))`), `Public`/`Private`
# (public means `Base.ispublic`, which exported names are), `Order` (categories) and
# `Filter`; plus each explicit `@docs` entry. Rendering is tracked per docstring
# (binding and signature), as `checkdocs` tracks it.
#
# Checked:
#   1. every `@ref` in a rendered docstring, a page under docs/src (the generated
#      tutorials excepted) or a registered Literate tutorial resolves: to a heading
#      anchor first (Documenter's `slugify`; a slug of several headings is an error,
#      and a code link captured by a heading is reported too), else to a rendered
#      docstring; an unqualified name in a docstring must be bound in its module;
#   2. every `@docs` entry names a documented binding;
#   3. every exported or public name Briareus owns has a docstring, and each of its
#      docstrings (signatures) is rendered by some block — stricter than `checkdocs`,
#      which ignores an exported name with no docstring at all;
#   4. no docstring is rendered twice (Documenter's "duplicate docs found");
#   5. the Markdown of every docstring, page and tutorial renders as written: no `_`
#      emphasis from bare identifiers, paths or subscripts, no broken code spans (see
#      `MDLint` below).
#
# Standalone: julia --project=. test/docrefs.jl. runtests.jl includes it first.

if !isdefined(Main, :Briareus)
    using Briareus
end
using Test

module DocRefs

using Briareus

const ROOT = normpath(joinpath(@__DIR__, ".."))
const DOCS_SRC = joinpath(ROOT, "docs", "src")
const TUTORIALS = joinpath(DOCS_SRC, "tutorials")   # generated by Literate; not scanned
const LITERATE = joinpath(ROOT, "docs", "literate")
const MAKE = joinpath(ROOT, "docs", "make.jl")

# The modules whose docstrings the build documents (`makedocs(; modules)`).
const MODULES = (Briareus,)

# The identifier a `@docs` entry or a code reference names: the last component of a
# possibly qualified name, with any call signature dropped.
function base_name(code::AbstractString)
    m = match(r"^\s*((?:[A-Za-z_][\w!]*\.)*)(@?[A-Za-z_\p{L}][\w!\p{L}\p{N}]*)", code)
    m === nothing && return nothing
    return String(m.captures[2])
end

# Pages Documenter renders: every markdown file under docs/src but the generated
# tutorials.
function pages()
    out = String[]
    for (root, _, files) in walkdir(DOCS_SRC)
        startswith(root, TUTORIALS) && continue
        for f in files
            endswith(f, ".md") && push!(out, joinpath(root, f))
        end
    end
    return sort(out)
end

# The Literate scripts docs/make.jl registers in `TUTORIALS` (others, such as the
# plotting helper, are not pages).
function tutorial_scripts(make = read(MAKE, String))
    m = match(r"const TUTORIALS = \[(.*?)\]"s, make)
    m === nothing && error("docs/make.jl: no `const TUTORIALS = [...]` list")
    return [joinpath(LITERATE, s.captures[1]) for s in eachmatch(r"\"([^\"]+\.jl)\"", m.captures[1])]
end

# The markdown of a Literate script: the text of its comment lines; a code line
# becomes a blank line so that line numbers match the script.
function literate_markdown(source::AbstractString)
    lines = String[]
    for line in eachline(IOBuffer(source))
        m = match(r"^#(?: (.*))?$", line)
        push!(lines, m === nothing || m.captures[1] === nothing ? "" : String(m.captures[1]))
    end
    return join(lines, "\n")
end

page_texts() = vcat([p => read(p, String) for p in pages()],
                    [f => literate_markdown(read(f, String)) for f in tutorial_scripts()])

# Fenced blocks of a page, as (lang, body, first line) for each ```lang fence.
function fenced_blocks(text::AbstractString)
    out = Tuple{String,Vector{String},Int}[]
    lang, body, start = nothing, String[], 0
    for (n, line) in enumerate(split(text, '\n'))
        s = strip(line)
        if lang === nothing
            m = match(r"^```\s*(\S*)", s)
            m === nothing || ((lang, body, start) = (String(m.captures[1]), String[], n))
        elseif startswith(s, "```")
            push!(out, (lang, body, start))
            lang = nothing
        else
            push!(body, String(line))
        end
    end
    return out
end

# Documenter's `slugify` (utilities.jl, Documenter 1.x), verbatim.
function slugify(s::AbstractString)
    s = replace(s, r"\s+" => "-")
    s = replace(s, r"&" => "-and-")
    s = replace(s, r"[^\p{L}\p{P}\d\-]+" => "")
    return String(strip(replace(s, r"\-\-+" => "-"), '-'))
end

# Heading anchors of every page (top-level headings outside fences), slug => places.
function headers(texts)
    anchors = Dict{String,Vector{String}}()
    for (page, text) in texts
        infence = false
        for (n, line) in enumerate(split(text, '\n'))
            s = rstrip(line)
            startswith(s, "```") && (infence = !infence; continue)
            infence && continue
            m = match(r"^#{1,6}\s+(.*?)\s*$", s)
            m === nothing && continue
            push!(get!(anchors, slugify(m.captures[1]), String[]),
                  "$(relpath(page, ROOT)):$n `$(s)`")
        end
    end
    return anchors
end

# Text outside fenced code blocks, where a `[x](@ref)` is not a link.
function unfenced(text::AbstractString)
    out, infence = String[], false
    for line in split(text, '\n')
        startswith(lstrip(line), "```") && (infence = !infence; push!(out, ""); continue)
        push!(out, infence ? "" : String(line))
    end
    return join(out, "\n")
end

# Every `@ref` link in `text`, as (link, slug, code): `slug` is what Documenter looks
# up among heading anchors, `code` the name a docstring lookup takes (`nothing` for a
# link that can only reach a heading).
function refs(text::AbstractString)
    out = Tuple{String,String,Union{String,Nothing}}[]
    for m in eachmatch(r"\[([^\[\]]*)\]\(@ref(?:\s+([^)]*?))?\s*\)", unfenced(text))
        label, target = m.captures
        link = replace(m.match, r"\s+" => " ")
        if target !== nothing
            quoted = match(r"\"(.+)\"", target)
            if quoted === nothing
                t = String(strip(target, '`'))
                push!(out, (link, t, t))
            else
                push!(out, (link, slugify(quoted.captures[1]), nothing))
            end
        else
            code = match(r"^`([^`]*)`$", strip(label))
            if code === nothing
                push!(out, (link, slugify(strip(label)), nothing))
            else
                push!(out, (link, String(code.captures[1]), String(code.captures[1])))
            end
        end
    end
    return out
end

# One docstring: a binding at a signature, with its text, source path and module.
struct Doc
    mod::Module
    name::String
    sig::Any
    text::String
    path::String
end
key(d::Doc) = (d.mod, d.name, d.sig)

# Every docstring of the documented modules. A module's own docstring is held by
# `Binding(M, nameof(M))`.
function docstrings(mods = MODULES)
    out = Doc[]
    for mod in mods, (binding, multidoc) in Base.Docs.meta(mod)
        binding isa Base.Docs.Binding || continue
        for (sig, docstr) in multidoc.docs
            parts = String[String(t) for t in docstr.text if t isa AbstractString]
            push!(out, Doc(binding.mod, String(binding.var), sig, join(parts, "\n"),
                           normpath(string(get(docstr.data, :path, "")))))
        end
    end
    return out
end

ispublic_name(mod, name) = isdefined(Base, :ispublic) ? Base.ispublic(mod, Symbol(name)) :
                                                        Base.isexported(mod, Symbol(name))

# Documenter's category of a binding (DocSystem.category).
function category(mod, name)
    startswith(name, "@") && return :macro
    isdefined(mod, Symbol(name)) || return :constant
    x = getfield(mod, Symbol(name))
    x isa Module ? :module : x isa Function ? :function :
        (x isa DataType || x isa UnionAll) ? :type : :constant
end

# The settings of an `@autodocs` block, evaluated as Documenter does (Filter in Main,
# the rest in the page's CurrentModule, Main here).
function autodocs_fields(body::Vector{String})
    fields = Dict{Symbol,Any}()
    ex = Meta.parseall(join(body, "\n"))
    for a in ex.args
        a isa Expr && a.head === :(=) || continue
        fields[a.args[1]] = Core.eval(Main, a.args[2])
    end
    return fields
end

# The docstrings an `@autodocs` block selects.
function autodocs_select(fields, docs)
    haskey(fields, :Modules) || return Doc[]
    mods = fields[:Modules]
    order = get(fields, :Order, [:module, :constant, :type, :function, :macro])
    pagelist = map(normpath, get(fields, :Pages, String[]))
    public, private = get(fields, :Public, true), get(fields, :Private, true)
    filt = get(fields, :Filter, x -> true)
    sel = Doc[]
    for d in docs
        d.mod in mods || continue
        p = ispublic_name(d.mod, d.name)
        (p && public) || (!p && private) || continue
        category(d.mod, d.name) in order || continue
        isempty(pagelist) || any(pg -> endswith(d.path, pg), pagelist) || continue
        Base.invokelatest(filt, getfield(d.mod, Symbol(d.name))) || continue
        push!(sel, d)
    end
    return sel
end

# Exported and public names a documented module owns (not re-exports).
function public_names(mods = MODULES)
    out = Tuple{Module,String}[]
    for mod in mods, n in names(mod)
        n === nameof(mod) && continue
        isdefined(mod, n) && Base.which(mod, n) === mod || continue
        push!(out, (mod, String(n)))
    end
    return out
end

"""
    check(; mods, docs, texts, exports) -> (; unresolved, unknown_entries, undocumented, duplicates, captured)

Run the checks over the docstrings `docs` and the page texts `texts` (page => markdown;
`@docs`/`@autodocs` blocks are read from these) and return the offenders as vectors of
lines; all empty means the docs build will resolve. `captured` lists code links to a
rendered docstring that resolve to a heading of the same slug instead.
"""
function check(; mods = MODULES, docs = docstrings(mods), texts = page_texts(),
               exports = public_names(mods))
    byname = Dict{Tuple{Module,String},Vector{Doc}}()
    for d in docs
        push!(get!(byname, (d.mod, d.name), Doc[]), d)
    end
    rendered = Dict{Any,Vector{String}}()     # key(doc) => where rendered
    unknown_entries = String[]
    for (page, text) in texts
        endswith(page, ".md") || continue      # Literate scripts carry no docs blocks
        where = relpath(page, ROOT)
        for (lang, body, start) in fenced_blocks(text)
            if lang == "@docs"
                for line in body
                    s = strip(line)
                    isempty(s) && continue
                    n = base_name(s)
                    hits = n === nothing ? Doc[] :
                        reduce(vcat, (get(byname, (m, n), Doc[]) for m in mods); init = Doc[])
                    if isempty(hits)
                        push!(unknown_entries, "$where: `@docs` entry `$s` is not a documented binding")
                    end
                    for d in hits
                        push!(get!(rendered, key(d), String[]), "$where:$start @docs")
                    end
                end
            elseif lang == "@autodocs"
                for d in autodocs_select(autodocs_fields(body), docs)
                    push!(get!(rendered, key(d), String[]), "$where:$start @autodocs")
                end
            end
        end
    end
    duplicates = ["`$(d.mod).$(d.name)` ($(relpath(d.path, ROOT))) is rendered " *
                  "$(length(rendered[key(d)])) times: $(join(rendered[key(d)], ", "))"
                  for d in docs if length(get(rendered, key(d), ())) > 1]
    rendered_names = Set(d.name for d in docs if haskey(rendered, key(d)))
    owners = Dict(d.name => d.mod for d in docs)
    anchors = headers(texts)
    unresolved, captured = String[], String[]
    binds(owner, target) = occursin('.', first(split(target, '('))) ||
        ((n = base_name(target)) !== nothing && isdefined(owner, Symbol(n)))
    function resolve!(where, link, slug, code, owner)
        places = get(anchors, slug, String[])
        if length(places) > 1
            push!(unresolved, "$where: $link is ambiguous: its slug `$slug` is the " *
                              "anchor of $(length(places)) headings, " * join(places, ", "))
        elseif length(places) == 1
            n = code === nothing ? nothing : base_name(code)
            n !== nothing && n in rendered_names &&
                push!(captured, "$where: $link resolves to the heading $(only(places)), " *
                                "not to the docstring of `$n`; qualify it " *
                                "([`$n`](@ref $(owners[n]).$n)) or rename the heading")
        elseif code === nothing
            push!(unresolved, "$where: $link names no heading")
        else
            n = base_name(code)
            n !== nothing && n in rendered_names ||
                push!(unresolved, "$where: $link names no rendered docstring" *
                      (n !== nothing && haskey(owners, n) ? " (`$n` has one, but no docs block renders it)" :
                       n !== nothing && any(m -> isdefined(m, Symbol(n)), mods) ?
                       " (`$n` has no docstring)" : ""))
            owner === nothing || binds(owner, code) ||
                push!(unresolved, "$where in $owner: $link is not bound there; qualify it")
        end
    end
    for d in docs
        haskey(rendered, key(d)) || continue
        for (link, slug, code) in refs(d.text)
            resolve!("docstring of `$(d.name)` ($(relpath(d.path, ROOT)))", link, slug, code, d.mod)
        end
    end
    for (page, text) in texts, (link, slug, code) in refs(text)
        resolve!(relpath(page, ROOT), link, slug, code, nothing)
    end
    undocumented = String[]
    for (mod, name) in exports
        ds = get(byname, (mod, name), Doc[])
        if isempty(ds)
            push!(undocumented, "public `$mod.$name` has no docstring (was it attached " *
                                "to something defined between it and its definition?)")
            continue
        end
        for d in ds
            haskey(rendered, key(d)) && continue
            push!(undocumented, "public `$mod.$name`" *
                  (d.sig === Union{} ? "" : " :: $(d.sig)") *
                  " has a docstring in $(relpath(d.path, ROOT)) that no docs block renders " *
                  "(is that file in an @autodocs `Pages` list?)")
        end
    end
    return (; unresolved, unknown_entries, undocumented, duplicates, captured)
end

# ---------------------------------------------------------------------------------------
# Markdown that renders other than written
# ---------------------------------------------------------------------------------------
#
# Documenter parses docstrings and pages with Julia's Markdown (the `julia` flavor), which
# is not CommonMark: an `_` inside a word opens emphasis, so a bare path such as
# VR/power_sources/x.html or a subscript such as n_e/n_c pairs with the next `_` in the
# paragraph, italicizes the text between and drops both underscores; a code span the
# emphasis swallowed half of then renders with literal backticks. The check parses each
# text with that flavor, its emphasis, math and interpolation parsers wrapped to mark
# what they produced, and walks the tree. Flagged:
#   - `_`/`__` emphasis (intended emphasis is written `*...*`);
#   - `*`/`**` emphasis opened inside a word (`T*` ... `P*`);
#   - `$...$` math and `$name` interpolation (math is written ``...``);
#   - a backtick or an HTML tag in rendered text (a code span that did not close; raw
#     HTML, which this Markdown prints as text);
#   - any other literal `_` in rendered text. It renders now, but the next `_` written in
#     the same paragraph pairs with it: identifiers, paths and subscripts go in code
#     (`n_e`) or math (``n_e``), or are escaped (`\_`).

module MDLint

using Markdown
const MD = Markdown

# A node produced by a wrapped parser, with the reason it was flagged.
struct Flagged <: MD.MarkdownElement
    kind::Symbol
    node::Any
end
# A backslash escape (`\_`), whose character is meant literally.
struct Escaped <: MD.MarkdownElement
    char::String
end

prevchar(stream::IO) = position(stream) == 0 ? ' ' :
    (skip(stream, -1); c = read(stream, Char); c)

# `f`, its result wrapped as `Flagged(kind, ·)` (with `intraword`, only when the
# delimiter follows a letter or digit).
function flagging(f, kind; intraword = false)
    g = function (stream::IO, md::MD.MD)
        p = position(stream)
        c = prevchar(stream)
        seek(stream, p)
        r = f(stream, md)
        r === nothing && return nothing
        intraword && !(isletter(c) || isdigit(c)) && return r
        return Flagged(kind, r)
    end
    MD.triggers!(g, MD.triggers(f))
    return g
end

function escaping(f)
    g = (stream::IO, md::MD.MD) -> (r = f(stream, md); r === nothing ? nothing : Escaped(r))
    MD.triggers!(g, MD.triggers(f))
    return g
end

function blockmath(stream::IO, md::MD.MD)
    MD.blocktex(stream, md) || return false
    push!(md, Flagged(:dollar_math, pop!(md.content)))
    return true
end

# The `julia` flavor with the parsers above swapped in.
const FLAVOR = let jl = MD.julia
    swap = Dict{Function,Function}(
        MD.underscore_italic => flagging(MD.underscore_italic, :underscore_emphasis),
        MD.underscore_bold => flagging(MD.underscore_bold, :underscore_emphasis),
        MD.asterisk_italic => flagging(MD.asterisk_italic, :intraword_asterisk; intraword = true),
        MD.asterisk_bold => flagging(MD.asterisk_bold, :intraword_asterisk; intraword = true),
        MD.tex => flagging(MD.tex, :dollar_math),
        MD.interp => flagging(MD.interp, :interpolation),
        MD.escapes => escaping(MD.escapes))
    inner = MD.InnerConfig(c => Function[get(swap, f, f) for f in fs] for (c, fs) in jl.inner)
    MD.Config(Function[f === MD.blocktex ? blockmath : f for f in jl.breaking],
              copy(jl.regular), inner)
end

const HTML_TAG = r"</?(?:a|b|i|em|strong|br|sub|sup|span|div|p|img|code|pre|table|tr|td|th|ul|ol|li|hr|h[1-6])\b[^>]*>"i
const ADVICE = Dict(
    :underscore_emphasis => "`_` opened emphasis (write intended emphasis as `*...*`; put identifiers, paths and subscripts in code or ``math``, or escape `\\_`)",
    :intraword_asterisk => "`*` inside a word opened emphasis (escape it, `\\*`, or use code)",
    :dollar_math => "`\$` math (write ``math``)",
    :interpolation => "`\$` interpolation in Markdown (escape `\\\$` or use code)",
    :backtick => "backtick in rendered text (a code span did not close; keep each span on one line, out of `_` emphasis)",
    :html => "HTML tag in rendered text (printed as text)",
    :underscore => "literal `_` in rendered text (the next `_` in the paragraph pairs with it: code, ``math`` or `\\_`)")

excerpt(x) = (s = replace(x isa AbstractString ? x : MD.plain(MD.Paragraph(Any[x])), r"\s+" => " ");
              s = strip(s); length(s) > 90 ? first(s, 87) * "..." : s)

const SKIPPED_FIELDS = (:url, :category, :language, :align, :ordered, :loose, :id, :title)

function walk!(out, x)
    if x isa Flagged
        push!(out, (x.kind, excerpt(x.node)))
        walk!(out, x.node)
    elseif x isa AbstractString
        occursin('`', x) && push!(out, (:backtick, excerpt(x)))
        occursin(HTML_TAG, x) && push!(out, (:html, excerpt(x)))
        occursin('_', x) && push!(out, (:underscore, excerpt(x)))
    elseif x isa Union{Escaped,MD.Code,MD.LaTeX,MD.HorizontalRule,MD.LineBreak,MD.Image}
    elseif x isa Union{Expr,Symbol}
        push!(out, (:interpolation, string(x)))
    elseif x isa AbstractVector
        foreach(y -> walk!(out, y), x)
    elseif x isa Union{MD.MarkdownElement,MD.MD}
        for f in fieldnames(typeof(x))
            f in SKIPPED_FIELDS || walk!(out, getfield(x, f))
        end
    end
    return out
end

"""
    issues(text) -> Vector{Tuple{Symbol,String}}

The places where the Markdown `text` renders other than written, as (kind, excerpt).
"""
issues(text::AbstractString) = walk!(Tuple{Symbol,String}[], MD.parse(text; flavor = FLAVOR))

end # module MDLint

"""
    markdown_issues(; docs, texts) -> Vector{String}

Every place in the docstrings `docs` and the page texts `texts` where the Markdown
renders other than written (see `MDLint`), one line each.
"""
function markdown_issues(; docs = docstrings(), texts = page_texts())
    out = String[]
    for d in docs, (kind, s) in MDLint.issues(d.text)
        push!(out, "docstring of `$(d.name)` ($(relpath(d.path, ROOT))): " *
                   "$(MDLint.ADVICE[kind]): «$s»")
    end
    for (page, text) in texts, (kind, s) in MDLint.issues(text)
        push!(out, "$(relpath(page, ROOT)): $(MDLint.ADVICE[kind]): «$s»")
    end
    return out
end

end # module DocRefs

@testset "docs cross-references resolve" begin
    r = DocRefs.check()
    for (label, lines) in (("@ref linked to a heading", r.captured),
                           ("unresolved @ref", r.unresolved),
                           ("unknown @docs entry", r.unknown_entries),
                           ("checkdocs = :exports would fail", r.undocumented),
                           ("duplicate docs", r.duplicates))
        foreach(line -> @warn("$label: $line"), lines)
    end
    @test isempty(r.captured)
    @test isempty(r.unresolved)
    @test isempty(r.unknown_entries)
    @test isempty(r.undocumented)
    @test isempty(r.duplicates)
end

@testset "docs Markdown renders as written" begin
    bad = DocRefs.markdown_issues()
    foreach(line -> @warn(line), bad)
    @test isempty(bad)
    # the guard itself: the failure it was written for, and text that must pass
    lint = DocRefs.MDLint.issues
    @test Set(first.(lint("See (VR/power_sources/x.html) and `visrad_spot`."))) ==
          Set([:underscore_emphasis, :backtick])
    @test isempty(lint("A *word*, **bold**, `a_b`, ``n_e``, a\\_b, [`f_g`](@ref) and\n\n```julia\nx_1 = 2\n```"))
    @test first.(lint("n_e only")) == [:underscore]
    @test :intraword_asterisk in first.(lint("T*a and P*b"))
end
