# Filters the `precompile` signatures of BriareusGUI/src/qt/first_frame.jl, the list the
# GUI's precompile workload replays. dev/gui_first_frame.jl includes this file and filters
# each new recording with it; run as a script, it filters the list in place:
#
#     julia dev/gui_first_frame_filter.jl [file]
#
# A signature is kept when every name in it is stable from one build to the next. Three
# kinds are dropped:
#
# - Signatures naming an anonymous closure by its numbers (`var"#95#96"`, `var"#_#81#83"`).
#   The compiler numbers these in the order it lowers a module, so any edit of that module
#   gives the name to another closure, and the replay then compiles the wrong method or
#   none.
# - Signatures naming a closure of BriareusGUI (`BriareusGUI.var"#f##0#f##1"`). These are
#   named after the function that holds them and counted within it, so they change with
#   each edit of the GUI.
# - Signatures of BriareusGUI's functions themselves (`typeof(BriareusGUI.f)` as the
#   callee). These belong in the workload of BriareusGUI/src/BriareusGUI.jl as explicit
#   calls or `precompile` statements.
#
# Closures of the dependencies that are named after their function (`GLMakie.var"#f##0#f##1"`)
# are kept: they change only with an update of the dependency, after which the list is
# recorded again.

const NUMBERED_CLOSURE = r"#\d+#\d+\""
const GUI_CLOSURE = r"BriareusGUI(\.\w+)*\.var\"#"
const GUI_CALLEE = r"^precompile\(Tuple\{typeof\(BriareusGUI\."

"Whether `line` is a `precompile` signature the replay keeps."
keep_signature(line::AbstractString) =
    startswith(line, "precompile(") && !occursin(NUMBERED_CLOSURE, line) &&
    !occursin(GUI_CLOSURE, line) && !occursin(GUI_CALLEE, line)

"The signatures of `lines` the replay keeps, sorted and without repeats."
filter_signatures(lines) = sort!(unique!(filter(keep_signature, collect(String, lines))))

"Write `lines` (signatures) to the replay list `path`."
function write_signatures(path::AbstractString, lines)
    open(path, "w") do io
        println(io, "# Generated by dev/gui_first_frame.jl: what the window's first frames compile.")
        foreach(l -> println(io, l), lines)
    end
    return path
end

if abspath(PROGRAM_FILE) == @__FILE__
    path = isempty(ARGS) ? joinpath(dirname(@__DIR__), "BriareusGUI", "src", "qt", "first_frame.jl") : ARGS[1]
    old = filter(l -> startswith(l, "precompile("), readlines(path))
    new = filter_signatures(old)
    write_signatures(path, new)
    println("kept $(length(new)) of $(length(old)) signatures in $path ($(length(old) - length(new)) dropped)")
end
